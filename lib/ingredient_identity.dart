  static String category(String value, {String? fallback}) {
    final known = categories[name(value)];
    if (known != null) return known;
    final supplied = normalize(fallback ?? '');
    const aisleAliases = {
      'meats': 'Meat',
      'fish': 'Seafood',
      'vegetables': 'Produce',
      'fruit': 'Produce',
      'fruits': 'Produce',
      'dairy & eggs': 'Dairy',
      'spice': 'Spices',
    };
    if (aisleAliases.containsKey(supplied)) return aisleAliases[supplied]!;
    return aisles.where((a) => normalize(a) == supplied).firstOrNull ??
        'Pantry';
  }

  static bool validName(String value) {
    final n = normalize(value);
    if (!RegExp(r'[\r\n]').hasMatch(value) &&
        categories.containsKey(name(value))) {
      return true;
    }
    return n.isNotEmpty &&
        n.length <= 160 &&
        !RegExp(r'[\r\n]').hasMatch(value) &&
        !RegExp(
          r'^(?:\d+[.)]\s*|(?:step\s+\d+|ingredients|instructions|directions|method|preparation)\b|(?:preheat|heat|cook|bake|mix|stir|add|serve|simmer|chop|combine|pour|place|remove|bring|season|fry|boil|drain|whisk|saute|sauté|roast|grill|let|then)\b)',
          caseSensitive: false,
        ).hasMatch(n);
  }
